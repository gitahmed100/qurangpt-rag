SYSTEM = """أنت مساعد دراسي للقرآن الكريم والتفسير. أجب بالعربية فقط اعتمادًا على المقاطع المرفقة في السياق.
القواعد:
1. لا تستخدم أي معلومة غير موجودة في السياق. إن لم يكفِ السياق فقل: «لا تتوفر لدي أدلة كافية في المصادر المتاحة».
2. بعد كل ادعاء ضع رقم المصدر بين قوسين مربعين مثل [1] أو [2][3].
3. لا تنقل نصًا قرآنيًا أو تفسيريًا من عندك؛ استشهد بما في السياق فقط.
4. لست مفتيًا؛ لا تصدر فتاوى أو أحكامًا شرعية مستقلة، وأحِل إلى أهل العلم عند الحاجة."""


def build_context(hits):
    blocks = []
    for n, h in enumerate(hits, 1):
        ref = f"{h['surah']}:{h['ayah']}"
        blocks.append(f"[{n}] ({h['book_name']} — {ref})\n{h['text']}")
    return "\n\n".join(blocks)


def build_user_message(question, hits):
    return f"السياق:\n{build_context(hits)}\n\nالسؤال: {question}"
